import { test, expect } from '@playwright/test';
test('staff workspace supports devices and rentals while hiding admin account management', async ({ page }) => {
  const id = '507f1f77bcf86cd799439011'; let status = 'pending'; let saved;
  const staff = { _id: id, fullName: 'Nhân viên An', role: 'staff' };
  await page.addInitScript(() => sessionStorage.setItem('techrental-access-token', 'test-token'));
  await page.route('**/api/v1/auth/me', route => route.fulfill({ json: { user: staff } }));
  await page.route('**/api/v1/admin/devices?*', route => route.fulfill({ json: { data: [], pagination: { total: 0, pages: 0 } } }));
  await page.route('**/api/v1/categories', route => route.fulfill({ json: { data: [{ _id: id, name: 'Máy tính' }] } }));
  await page.route('**/api/v1/admin/devices', route => { saved = route.request().postDataJSON(); return route.fulfill({ status: 201, json: { data: { _id: id, ...saved } } }); });
  await page.route('**/api/v1/admin/requests?*', route => route.fulfill({ json: { data: [{ _id: id, status, quantity: 1, contact: { name: 'Khách hàng' }, device: { name: 'Laptop', assetCode: 'LT-01' }, startAt: '2030-01-01', endAt: '2030-01-08', rentalAmount: 700000 }], pagination: { total: 1, pages: 1 } } }));
  await page.route(`**/api/v1/admin/requests/${id}/approve`, route => { status = 'approved'; return route.fulfill({ json: { data: { _id: id, status } } }); });
  await page.goto('/nhan-vien/quan-ly/devices');
  await expect(page.getByText('Không gian nhân viên', { exact: true })).toBeVisible();
  await expect(page.getByRole('link', { name: 'Quản lý nhân viên', exact: true })).toHaveCount(0);
  await expect(page.getByRole('link', { name: 'Tài khoản', exact: true })).toHaveCount(0);
  await expect(page.getByRole('link', { name: 'Tin nhắn khách hàng', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Thêm thiết bị', exact: true }).click();
  await page.getByLabel('Tên thiết bị', { exact: true }).fill('Laptop nhân viên thêm');
  await page.getByLabel('Mã tài sản', { exact: true }).fill('STAFF-01');
  await page.getByRole('combobox', { name: 'Danh mục', exact: true }).selectOption(id);
  await page.getByLabel('Giá thuê / ngày (VND)').fill('100000');
  await page.getByRole('button', { name: 'Lưu thiết bị', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Đã lưu thiết bị');
  expect(saved.name).toBe('Laptop nhân viên thêm');
  await page.getByRole('link', { name: 'Yêu cầu thuê', exact: true }).click();
  await page.getByRole('button', { name: 'Duyệt đơn', exact: true }).click();
  await page.getByRole('button', { name: 'Xác nhận duyệt', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Giao hàng', exact: true })).toBeVisible();
  await page.goto('/admin/staff');
  await expect(page).toHaveURL(/nhan-vien\/quan-ly\/devices$/);
  await expect(page.getByRole('heading', { name: 'Thiết bị', exact: true })).toBeVisible();
});
