test('admin edits availability, confirms deletion and sees active rental errors', async ({ page }) => {
  const id = '507f1f77bcf86cd799439011';
  const category = { _id: id, name: 'Máy tính' };
  let device = { _id: id, name: 'Laptop kiểm tra', assetCode: 'LT-TEST', category, status: 'available', rentalPricePerDay: 100000, isPublished: true, images: [] };
  let deletions = 0;
  await page.addInitScript(() => sessionStorage.setItem('techrental-access-token', 'test-token'));
  await page.route('**/api/v1/auth/me', route => route.fulfill({ json: { user: admin } }));
  await page.route('**/api/v1/admin/overview', route => route.fulfill({ json: { data: {} } }));
  await page.route('**/api/v1/categories', route => route.fulfill({ json: { data: [category] } }));
  await page.route('**/api/v1/admin/devices?*', route => route.fulfill({ json: { data: device ? [device] : [], pagination: { total: device ? 1 : 0, pages: device ? 1 : 0 } } }));
  await page.route(`**/api/v1/admin/devices/${id}`, route => {
    if (route.request().method() === 'PATCH') { device = { ...device, ...route.request().postDataJSON(), category }; return route.fulfill({ json: { data: device } }); }
    deletions++;
    if (device.status === 'borrowed') return route.fulfill({ status: 409, json: { message: 'Thiết bị đang cho thuê. Vui lòng xử lý yêu cầu trước khi xóa.' } });
    device = null; return route.fulfill({ json: { data: { _id: id } } });
  });
  await page.goto('/admin/devices');
  await page.getByRole('button', { name: 'Sửa Laptop kiểm tra' }).click();
  await page.getByRole('combobox', { name: 'Trạng thái', exact: true }).selectOption('borrowed');
  await page.getByRole('button', { name: 'Lưu thiết bị' }).click();
  await expect(page.getByRole('cell', { name: 'Đã cho thuê', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Xóa Laptop kiểm tra' }).click();
  let dialog = page.getByRole('dialog', { name: 'Xóa thiết bị?' });
  await dialog.getByRole('button', { name: 'Hủy', exact: true }).click();
  expect(deletions).toBe(0);
  await page.getByRole('button', { name: 'Xóa Laptop kiểm tra' }).click();
  await dialog.getByRole('button', { name: 'Xác nhận xóa' }).click();
  await expect(dialog.getByRole('alert')).toContainText('Thiết bị đang cho thuê');
  await dialog.getByRole('button', { name: 'Hủy', exact: true }).click();
  await page.getByRole('button', { name: 'Sửa Laptop kiểm tra' }).click();
  await page.getByRole('combobox', { name: 'Trạng thái', exact: true }).selectOption('available');
  await page.getByRole('button', { name: 'Lưu thiết bị' }).click();
  await page.getByRole('button', { name: 'Xóa Laptop kiểm tra' }).click();
  await dialog.getByRole('button', { name: 'Xác nhận xóa' }).click();
  await expect(page.getByRole('status')).toContainText('Đã xóa thiết bị thành công');
  await expect(page.getByRole('button', { name: 'Xóa Laptop kiểm tra' })).toHaveCount(0);
});
