import { test, expect } from '@playwright/test';
test('profile saves phone, gender and birthday; password form confirms and renews session', async ({ page }) => {
  let user = { fullName: 'Nguyễn Văn An', email: 'an@example.com', role: 'renter', phone: '', gender: '', birthDate: '' };
  let passwordCalls = 0;
  await page.addInitScript(() => sessionStorage.setItem('techrental-access-token', 'old-token'));
  await page.route('**/api/v1/auth/me', route => {
    if (route.request().method() === 'PATCH') user = { ...user, ...route.request().postDataJSON() };
    return route.fulfill({ json: { user } });
  });
  await page.route('**/api/v1/notifications?*', route => route.fulfill({ json: { data: [], unreadCount: 0, pagination: { total: 0, totalPages: 0 } } }));
  await page.route('**/api/v1/auth/change-password', route => { passwordCalls++; return route.fulfill({ json: { user, accessToken: 'new-token' } }); });
  await page.goto('/tai-khoan');
  await page.getByLabel('Số điện thoại', { exact: true }).fill('0988123456');
  await page.getByRole('combobox', { name: 'Giới tính', exact: true }).selectOption('male');
  await page.getByLabel('Ngày sinh', { exact: true }).fill('2004-07-01');
  await page.getByRole('button', { name: 'Lưu thay đổi' }).click();
  await expect(page.getByText('Đã lưu thông tin tài khoản.')).toBeVisible();
  await page.reload();
  await expect(page.getByLabel('Số điện thoại', { exact: true })).toHaveValue('0988123456');
  await expect(page.getByLabel('Ngày sinh', { exact: true })).toHaveValue('2004-07-01');
  await page.getByLabel('Mật khẩu hiện tại', { exact: true }).fill('OldPassword123');
  await page.getByLabel('Mật khẩu mới', { exact: true }).fill('NewPassword123');
  await page.getByLabel('Xác nhận mật khẩu mới', { exact: true }).fill('WrongPassword123');
  await page.getByRole('button', { name: 'Đổi mật khẩu', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('Mật khẩu xác nhận chưa khớp');
  expect(passwordCalls).toBe(0);
  await page.getByLabel('Xác nhận mật khẩu mới', { exact: true }).fill('NewPassword123');
  await page.getByRole('button', { name: 'Đổi mật khẩu', exact: true }).click();
  await expect(page.getByText('Đổi mật khẩu thành công. Các phiên đăng nhập khác đã hết hiệu lực.')).toBeVisible();
  expect(await page.evaluate(() => sessionStorage.getItem('techrental-access-token'))).toBe('new-token');
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
test('approval notification shows unread badge, marks read and opens customer orders', async ({ page }) => {
  const id = '507f1f77bcf86cd799439011'; let unread = true;
  await page.addInitScript(() => sessionStorage.setItem('techrental-access-token', 'test-token'));
  await page.route('**/api/v1/auth/me', route => route.fulfill({ json: { user: { fullName: 'Khách hàng', email: 'test@example.com', role: 'renter' } } }));
  await page.route('**/api/v1/notifications?*', route => route.fulfill({ json: { data: [{ _id: id, title: 'Yêu cầu thuê đã được duyệt', message: 'Yêu cầu thuê màn hình đã được duyệt.', readAt: unread ? null : '2026-11-16', createdAt: '2026-11-16' }], unreadCount: unread ? 1 : 0, pagination: { total: 1, totalPages: 1 } } }));
  await page.route(`**/api/v1/notifications/${id}/read`, route => { unread = false; return route.fulfill({ json: { data: { _id: id } } }); });
  await page.route('**/api/v1/rental-requests/mine', route => route.fulfill({ json: { data: [] } }));
  await page.goto('/tai-khoan');
  await expect(page.getByLabel('1 thông báo chưa đọc', { exact: true })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Thông báo', exact: true }).click();
  const dropdown = page.getByRole('region', { name: 'Danh sách thông báo' });
  await expect(dropdown.getByText('Yêu cầu thuê đã được duyệt')).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await dropdown.getByRole('button', { name: /Yêu cầu thuê đã được duyệt/ }).click();
  await expect(page).toHaveURL(/yeu-cau-thue$/);
  await expect(page.getByLabel('1 thông báo chưa đọc', { exact: true })).toHaveCount(0);
  expect(unread).toBe(false);
});
