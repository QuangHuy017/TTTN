import { Router } from 'express';
import { getHealth } from '../controllers/health.controller.js';
import { getDevices, getCategories, getDevice } from '../controllers/device.controller.js';
import authRouter, { userRouter } from './auth.routes.js';
import rentalRouter from './rental.routes.js';
import adminRouter from './admin.routes.js';
import favoriteRouter from './favorite.routes.js';
import notificationRouter from './notification.routes.js';
import chatRouter from './chat.routes.js';
const router = Router();
router.get('/health', getHealth);
router.get('/devices', getDevices);
router.get('/devices/:id', getDevice);
router.get('/categories', getCategories);
router.use('/auth', authRouter);
router.use('/rental-requests', rentalRouter);
router.use('/users', userRouter);
router.use('/admin', adminRouter);
router.use('/favorites', favoriteRouter);
router.use('/notifications', notificationRouter);
router.use('/chat', chatRouter);
export default router;
