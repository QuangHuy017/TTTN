import test from 'node:test';
import assert from 'node:assert/strict';
import request from 'supertest';
import mongoose from 'mongoose';
import app from '../src/app.js';
import User from '../src/models/User.js';
import Conversation from '../src/models/Conversation.js';
import ChatMessage from '../src/models/ChatMessage.js';
import { assertChatAccess, parseChatMessage, sendChatMessage, readChat } from '../src/services/chat.service.js';
import { signAccessToken } from '../src/utils/token.js';
import { env } from '../src/config/env.js';
env.jwtSecret = 'chat-tests-only-secret-12345678901234567890';
const id = '507f1f77bcf86cd799439011', otherId = '507f1f77bcf86cd799439012', roomId = '507f1f77bcf86cd799439013';
const customer = { _id: id, fullName: 'Khách hàng', role: 'renter', isActive: true };
const employee = { _id: otherId, fullName: 'Nhân viên', role: 'staff', isActive: true };
test('chat only allows the owning customer or staff/admin, validates content and nonce', () => {
  assert.doesNotThrow(() => assertChatAccess({ customer: id }, customer));
  assert.doesNotThrow(() => assertChatAccess({ customer: id }, employee));
  assert.doesNotThrow(() => assertChatAccess({ customer: { _id: id } }, { ...employee, role: 'admin' }));
  assert.throws(() => assertChatAccess({ customer: otherId }, customer), error => error.status === 404);
  for (const body of [null, { content: '' }, { content: 'x'.repeat(2001), clientId: 'a'.repeat(20) }, { content: { $ne: null }, clientId: 'a'.repeat(20) }, { content: 'Hello', clientId: 'short' }]) assert.throws(() => parseChatMessage(body), error => error.status === 400);
  assert.deepEqual(parseChatMessage({ content: ' Hello\nthere ', clientId: 'a'.repeat(20), sender: 'forged' }), { content: 'Hello\nthere', clientId: 'a'.repeat(20) });
});
test('chat endpoints require authentication and customers cannot open staff inbox or another customer history', async t => {
  for (const [method, path] of [['get', '/summary'], ['post', '/mine'], ['get', '/conversations'], ['get', `/conversations/${roomId}/messages`], ['post', `/conversations/${roomId}/messages`], ['patch', `/conversations/${roomId}/read`]]) assert.equal((await request(app)[method](`/api/v1/chat${path}`)).status, 401);
  t.mock.method(User, 'findById', async () => customer);
  t.mock.method(Conversation, 'findById', () => ({ populate: async () => ({ customer: otherId }) }));
  const auth = call => call.set('Authorization', `Bearer ${signAccessToken(customer)}`);
  assert.equal((await auth(request(app).get('/api/v1/chat/conversations'))).status, 403);
  assert.equal((await auth(request(app).get(`/api/v1/chat/conversations/${roomId}/messages`))).status, 404);
  assert.equal((await auth(request(app).get('/api/v1/chat/conversations/invalid/messages'))).status, 400);
});
test('message transaction allocates order, records the verified sender and retries idempotently', async t => {
  const session = {};
  const room = { _id: roomId, customer: id, sequence: 0, customerUnread: 0, staffUnread: 0 };
  t.mock.method(mongoose.connection, 'transaction', async callback => callback(session));
  t.mock.method(Conversation, 'findOneAndUpdate', async () => room);
  let saved = null;
  t.mock.method(ChatMessage, 'findOne', filter => ({ session: async () => saved?.clientId === filter.clientId && String(saved.sender) === String(filter.sender) ? saved : null }));
  const create = t.mock.method(ChatMessage, 'create', async (data, options) => { assert.equal(options.session, session); saved = { ...data[0], _id: otherId, createdAt: new Date() }; return [saved]; });
  const update = t.mock.method(Conversation, 'updateOne', async (_filter, changes) => { Object.assign(room, changes.$set); return { modifiedCount: 1 }; });
  const body = { content: 'Tư vấn giúp tôi', clientId: 'a'.repeat(20), senderRole: 'admin', sender: otherId };
  const first = await sendChatMessage(roomId, customer, body);
  assert.equal(first.sequence, 1);
  assert.equal(first.sender, id);
  assert.equal(first.senderRole, 'renter');
  assert.equal(update.mock.calls[0].arguments[1].$inc.staffUnread, 1);
  assert.equal((await sendChatMessage(roomId, customer, body)).sequence, 1);
  assert.equal(create.mock.calls.length, 1);
  await sendChatMessage(roomId, employee, { content: 'Chào bạn!', clientId: 'b'.repeat(20) });
  assert.equal(create.mock.calls[1].arguments[0][0].sequence, 2);
  assert.equal(update.mock.calls[1].arguments[1].$inc.customerUnread, 1);
});
test('read markers clamp to delivered sequence and only count messages from the other side', async t => {
  t.mock.method(mongoose.connection, 'transaction', async callback => callback({}));
  t.mock.method(Conversation, 'findOneAndUpdate', async () => ({ _id: roomId, customer: id, sequence: 10, customerReadSequence: 3 }));
  const count = t.mock.method(ChatMessage, 'countDocuments', () => ({ session: async () => 2 }));
  const update = t.mock.method(Conversation, 'updateOne', async () => ({}));
  const data = await readChat(roomId, customer, 6);
  assert.equal(data.throughSequence, 6);
  assert.deepEqual(count.mock.calls[0].arguments[0].senderRole, { $in: ['staff', 'admin'] });
  assert.equal(update.mock.calls[0].arguments[1].$set.customerUnread, 2);
  assert.equal((await readChat(roomId, customer, 100)).throughSequence, 10);
  await assert.rejects(readChat(roomId, customer, -1), error => error.status === 400);
});
test('customer conversation creation ignores client-supplied owner and staff can access inbox', async t => {
  let account = customer;
  t.mock.method(User, 'findById', async () => account);
  const create = t.mock.method(Conversation, 'findOneAndUpdate', async () => ({ _id: roomId, customer: id }));
  const result = await request(app).post('/api/v1/chat/mine').set('Authorization', `Bearer ${signAccessToken(customer)}`).send({ customer: otherId });
  assert.equal(result.status, 200);
  assert.equal(create.mock.calls[0].arguments[0].customer, id);
  account = employee;
  const chain = { populate: () => chain, sort: () => chain, skip: () => chain, limit: () => chain, lean: async () => [] };
  t.mock.method(Conversation, 'find', () => chain);
  t.mock.method(Conversation, 'countDocuments', async () => 0);
  assert.equal((await request(app).get('/api/v1/chat/conversations').set('Authorization', `Bearer ${signAccessToken(employee)}`)).status, 200);
});
