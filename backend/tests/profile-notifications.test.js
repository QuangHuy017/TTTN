import test from 'node:test';
import assert from 'node:assert/strict';
import request from 'supertest';
import app from '../src/app.js';
import User from '../src/models/User.js';
import Notification from '../src/models/Notification.js';
import { parseProfile } from '../src/validators/profile.js';
import { signAccessToken } from '../src/utils/token.js';
import { env } from '../src/config/env.js';
env.jwtSecret = 'profile-notification-test-secret-1234567890';
const id = '507f1f77bcf86cd799439011';
const user = { _id: id, fullName: 'Test User', email: 'test@example.com', role: 'renter', isActive: true };
test('profile validates optional phone, gender and real birth dates without privilege changes', () => {
  assert.deepEqual(parseProfile({ phone: ' 0988123456 ', gender: 'female', birthDate: '2000-02-29' }), { phone: '0988123456', gender: 'female', birthDate: '2000-02-29' });
  for (const body of [{ phone: 'abc' }, { phone: 123456789 }, { gender: 'invalid' }, { birthDate: '2025-02-29' }, { birthDate: '2999-01-01' }, { birthDate: { $ne: null } }, { role: 'admin' }]) assert.throws(() => parseProfile(body), error => error.status === 400);
  assert.deepEqual(parseProfile({ phone: '', gender: '', birthDate: '' }), { phone: '', gender: '', birthDate: '' });
});
test('password changes require current password, renew the token and revoke old sessions', async t => {
  let account = { ...user, password: 'OldPassword123', tokenVersion: 0 };
  t.mock.method(User, 'findById', () => ({ then: resolve => resolve(account), select: async () => account }));
  const update = t.mock.method(User, 'findOneAndUpdate', async (_filter, changes) => { account = { ...account, ...changes.$set, tokenVersion: 1 }; return account; });
  const oldToken = signAccessToken(account);
  const change = body => request(app).post('/api/v1/auth/change-password').set('Authorization', `Bearer ${oldToken}`).send(body);
  assert.equal((await change({ currentPassword: 'WrongPassword', newPassword: 'NewPassword123' })).status, 400);
  assert.equal(update.mock.calls.length, 0);
  assert.equal((await change({ currentPassword: 'OldPassword123', newPassword: 'OldPassword123' })).status, 400);
  const result = await change({ currentPassword: 'OldPassword123', newPassword: 'NewPassword123' });
  assert.equal(result.status, 200);
  assert.equal(account.password, 'NewPassword123');
  assert.equal(result.body.user.password, undefined);
  assert.equal(result.body.user.passwordHash, undefined);
  assert.deepEqual(update.mock.calls[0].arguments[1].$unset, { passwordHash: '' });
  assert.equal((await request(app).get('/api/v1/auth/me').set('Authorization', `Bearer ${oldToken}`)).status, 401);
  assert.equal((await request(app).get('/api/v1/auth/me').set('Authorization', `Bearer ${result.body.accessToken}`)).status, 200);
});
test('notifications require login and queries and read updates belong to the current user', async t => {
  assert.equal((await request(app).get('/api/v1/notifications')).status, 401);
  t.mock.method(User, 'findById', async () => user);
  const queries = [];
  t.mock.method(Notification, 'find', filter => { queries.push(filter); const chain = { sort: () => chain, skip: () => chain, limit: () => chain, lean: async () => [] }; return chain; });
  t.mock.method(Notification, 'countDocuments', async filter => { queries.push(filter); return 0; });
  const all = t.mock.method(Notification, 'updateMany', async () => ({ modifiedCount: 0 }));
  const one = t.mock.method(Notification, 'findOneAndUpdate', async () => null);
  const auth = call => call.set('Authorization', `Bearer ${signAccessToken(user)}`);
  const list = await auth(request(app).get('/api/v1/notifications'));
  assert.equal(list.status, 200);
  for (const query of queries) assert.equal(query.user, id);
  assert.equal((await auth(request(app).patch(`/api/v1/notifications/${id}/read`))).status, 404);
  assert.deepEqual(one.mock.calls[0].arguments[0], { _id: id, user: id });
  assert.equal((await auth(request(app).patch('/api/v1/notifications/read-all'))).status, 200);
  assert.deepEqual(all.mock.calls[0].arguments[0], { user: id, readAt: null });
});
